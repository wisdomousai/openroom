// Precompiles OpenRoom JSON Schemas into eval-free validator code.
// Cloudflare Workers (workerd) forbid runtime code generation (`new Function`),
// which Ajv's normal compile path uses — so the validator must be generated at
// build time via Ajv standalone codegen. Output: src/generated/validator.js.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import Ajv2020Module from 'ajv/dist/2020.js';
import standaloneModule from 'ajv/dist/standalone/index.js';

const Ajv2020 = Ajv2020Module.default ?? Ajv2020Module;
const standaloneCode = standaloneModule.default ?? standaloneModule;

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, '..');
const sessionSchema = JSON.parse(
  readFileSync(join(pkgRoot, 'schema', 'session.schema.json'), 'utf8'),
);
const outlineSchema = JSON.parse(
  readFileSync(join(pkgRoot, 'schema', 'outline.schema.json'), 'utf8'),
);

// A saved deck may be unfinished. Derive its interaction shape from the live
// contract, relaxing only editable content; ids, references and limits stay
// strict. Publish the derived schema so file/API clients see the same contract.
const draftSessionSchema = structuredClone(sessionSchema);
draftSessionSchema.$id = 'https://openroom.app/schema/draft-session.schema.json';
draftSessionSchema.title = 'Draft session content';
const draftDefs = draftSessionSchema.$defs;
delete draftDefs.interaction.properties.prompt.minLength;
delete draftDefs.option.properties.label.minLength;
delete draftDefs.rankingOption.properties.label.minLength;
for (const branch of draftDefs.interaction.allOf) {
  if (branch.if.properties.type.const !== 'fill-the-gaps') continue;
  branch.then.properties.gaps.minItems = 0;
  delete branch.then.properties.gaps.items.properties.answers.items.minLength;
}
writeFileSync(join(pkgRoot, 'schema', 'draft-session.schema.json'), `${JSON.stringify(draftSessionSchema, null, 2)}\n`);

const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  allowUnionTypes: true,
  code: { source: true, esm: true },
});
const sessionValidate = ajv.compile(sessionSchema);
const draftSessionValidate = ajv.compile(draftSessionSchema);
const outlineValidate = ajv.compile(outlineSchema);

function generatedCode(validate) {
  let code = standaloneCode(ajv, validate);

// Ajv standalone emits CJS `require(...)` for its runtime helpers even in esm
// mode. Mixed export+require makes Node reject the file outright
// (ERR_AMBIGUOUS_MODULE_SYNTAX), so rewrite each helper into a hoisted import.
  const imports = [];
  code = code.replace(
    /const (\w+) = require\("([^"]+)"\)\.default;/g,
    (_match, name, specifier) => {
      const withExt = specifier.endsWith('.js') ? specifier : `${specifier}.js`;
      imports.push(`import ${name}$module from ${JSON.stringify(withExt)};`);
      return `const ${name} = ${name}$module.default ?? ${name}$module;`;
    },
  );
  if (/require\(/.test(code)) {
    throw new Error('[compile-validator] unhandled require() left in generated code');
  }
  return `${imports.join('\n')}\n${code}`;
}

const outDir = join(pkgRoot, 'src', 'generated');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'validator.js'), `// GENERATED by scripts/compile-validator.mjs — do not edit.\n${generatedCode(sessionValidate)}`);
writeFileSync(join(outDir, 'draft-validator.js'), `// GENERATED by scripts/compile-validator.mjs — do not edit.\n${generatedCode(draftSessionValidate)}`);
writeFileSync(join(outDir, 'draft-validator.d.ts'), `import type { ValidateFunction } from 'ajv';\ndeclare const validate: ValidateFunction;\nexport default validate;\n`);
writeFileSync(
  join(outDir, 'validator.d.ts'),
  `import type { ValidateFunction } from 'ajv';\ndeclare const validate: ValidateFunction;\nexport default validate;\n`,
);
writeFileSync(join(outDir, 'outline-validator.js'), `// GENERATED by scripts/compile-validator.mjs — do not edit.\n${generatedCode(outlineValidate)}`);
writeFileSync(
  join(outDir, 'outline-validator.d.ts'),
  `import type { ValidateFunction } from 'ajv';\ndeclare const validate: ValidateFunction;\nexport default validate;\n`,
);
console.log('[compile-validator] wrote session and outline validators');
